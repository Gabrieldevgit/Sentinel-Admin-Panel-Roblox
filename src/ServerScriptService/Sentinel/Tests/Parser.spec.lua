-- Tests for Core/Parser: Tokenizer, CommandParser, DurationParser, QuantityParser.
return function(t)
	local Parser = script.Parent.Parent:WaitForChild("Core"):WaitForChild("Parser")
	local Tokenizer = require(Parser:WaitForChild("Tokenizer"))
	local CommandParser = require(Parser:WaitForChild("CommandParser"))
	local DurationParser = require(Parser:WaitForChild("DurationParser"))
	local QuantityParser = require(Parser:WaitForChild("QuantityParser"))

	t.test("tokenize keeps quoted strings together", function()
		local tokens = Tokenizer.Tokenize('ban Player1:30m "fly hacking" now')
		t.eq(#tokens, 4)
		t.eq(tokens[3], "fly hacking")
	end)

	t.test("split chain on &&, ignoring && inside quotes", function()
		local segs = Tokenizer.SplitChain('freeze all && announce "a && b"')
		t.eq(#segs, 2)
		t.eq(segs[2], 'announce "a && b"')
	end)

	t.test("target:modifier split", function()
		local target, mod = Tokenizer.SplitTargetModifier("Player1:30m")
		t.eq(target, "Player1")
		t.eq(mod, "30m")
		local t2, m2 = Tokenizer.SplitTargetModifier("Player1:")
		t.eq(t2, "Player1")
		t.eq(m2, nil)
	end)

	t.test("parse line builds command, modifier and arguments", function()
		local cmd = CommandParser.ParseLine("Ban Player1:1d Exploiting hard")
		t.ok(cmd)
		t.eq(cmd.CommandName, "ban")
		t.eq(cmd.Modifier, "1d")
		t.eq(cmd.TargetSelectors[1].Kind, "Named")
		t.eq(#cmd.Arguments, 2)
	end)

	t.test("chained commands link via NextCommand", function()
		local cmd = CommandParser.ParseLine("freeze all && kick others")
		t.eq(cmd.CommandName, "freeze")
		t.eq(cmd.TargetSelectors[1].Kind, "All")
		t.ok(cmd.NextCommand)
		t.eq(cmd.NextCommand.TargetSelectors[1].Kind, "Others")
	end)

	t.test("comma multi-target with # tag", function()
		local cmd = CommandParser.ParseLine("heal me,Player2,#vip")
		local s = cmd.TargetSelectors
		t.eq(#s, 3)
		t.eq(s[1].Kind, "Self")
		t.eq(s[2].Kind, "Named")
		t.eq(s[3].Kind, "Tag")
		t.eq(s[3].Value, "vip")
	end)

	t.test("@team takes the next token as its value", function()
		local cmd = CommandParser.ParseLine("kick @team Red Spamming")
		t.eq(cmd.TargetSelectors[1].Kind, "Team")
		t.eq(cmd.TargetSelectors[1].Value, "Red")
		t.eq(#cmd.Arguments, 1)
		t.eq(cmd.Arguments[1], "Spamming")
	end)

	t.test("@staff / @vip need no value token", function()
		local cmd = CommandParser.ParseLine("announce @staff Meeting now")
		t.eq(cmd.TargetSelectors[1].Value, "Staff")
		t.eq(cmd.Arguments[1], "Meeting")
	end)

	t.test("property selector consumes its comparison token", function()
		local cmd = CommandParser.ParseLine("give @level >25 Sword")
		t.eq(cmd.TargetSelectors[1].Kind, "Property")
		t.eq(cmd.TargetSelectors[1].Operator, ">")
		t.eq(cmd.TargetSelectors[1].Comparand, "25")
		t.eq(cmd.Arguments[1], "Sword")
	end)

	t.test("where filters are stripped from arguments", function()
		local cmd = CommandParser.ParseLine("kill all where Health<50")
		t.eq(#cmd.Arguments, 0)
	end)

	t.test("durations", function()
		t.eq(DurationParser.Parse("30m").Seconds, 1800)
		t.eq(DurationParser.Parse("2d").Seconds, 172800)
		t.eq(DurationParser.Parse("1mo").Seconds, 2592000)
		t.ok(DurationParser.Parse("perm").IsPermanent)
		t.eq(DurationParser.Parse("xyz"), nil)
		t.eq(DurationParser.Parse("0m"), nil)
		t.eq(DurationParser.Parse("5q"), nil)
	end)

	t.test("quantities", function()
		t.eq(QuantityParser.Parse("5").Amount, 5)
		t.eq(QuantityParser.Parse("-2.5").Amount, -2.5)
		t.eq(QuantityParser.Parse("Sword"), nil)
	end)
end
